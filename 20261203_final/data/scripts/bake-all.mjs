// `npm run bake`: rebuilds every file in data/baked/ from data/raw/ (ROADMAP M1.6), in order, and
// writes data/baked/MANIFEST.json with the SHA-256 and size of every input and output.
// `npm run bake:verify`: bakes again and fails unless every output is byte-for-byte the same
// (the bake is deterministic: same raw input, same bytes).
// The raw downloads come from `npm run fetch`; the DEM and point-cloud steps download into their
// caches only when the cache is missing.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const STEPS = ['bake-meta', 'bake-osm', 'bake-terrain', 'bake-trees', 'bake-weather', 'bake-world', 'bake-rays'];
const here = new URL('./', import.meta.url);
const baked = new URL('../baked/', import.meta.url);
const raw = new URL('../raw/', import.meta.url);
const verify = process.argv.includes('--verify');

const sha = (buf) => createHash('sha256').update(buf).digest('hex');
function listFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((f) => {
    const u = new URL(f, dir);
    return statSync(u).isDirectory() ? listFiles(new URL(`${f}/`, dir), base) : [u.pathname.slice(base.pathname.length)];
  }).filter((f) => !/^preview|\.png$/.test(f.split('/').pop())).sort();
}
const describe = (dir, files) => Object.fromEntries(files.map((f) => {
  const buf = readFileSync(new URL(f, dir));
  return [f, { bytes: buf.length, gzip: gzipSync(buf, { level: 9 }).length, sha256: sha(buf) }];
}));
const outputs = () => describe(baked, listFiles(baked).filter((f) => f !== 'MANIFEST.json' && f !== 'LICENSE.md'));

const before = verify ? outputs() : null;
const t0 = Date.now();
for (const step of STEPS) {
  const t = Date.now();
  execFileSync(process.execPath, ['--disable-warning=UNDICI-EHPA', new URL(`${step}.mjs`, here).pathname], { stdio: ['ignore', 'pipe', 'inherit'], env: { ...process.env, NODE_USE_ENV_PROXY: '1' } });
  console.log(`  ${step.padEnd(13)} ${((Date.now() - t) / 1000).toFixed(1)} s`);
}
const out = outputs();
const gzipTotal = Object.values(out).reduce((s, f) => s + f.gzip, 0);
const manifest = {
  note: 'Generated by npm run bake. Hashes of the raw inputs (data/raw, not committed) and the baked outputs.',
  steps: STEPS, gzipTotalMB: +(gzipTotal / 1e6).toFixed(3),
  inputs: describe(raw, listFiles(raw)), outputs: out,
};
writeFileSync(new URL('MANIFEST.json', baked), JSON.stringify(manifest, null, 2) + '\n');
console.log(`baked ${Object.keys(out).length} files in ${((Date.now() - t0) / 1000).toFixed(1)} s; gzip total ${manifest.gzipTotalMB} MB`);

if (verify) {
  const changed = Object.keys({ ...before, ...out }).filter((f) => before[f]?.sha256 !== out[f]?.sha256);
  if (changed.length) { console.error(`NOT reproducible: ${changed.join(', ')}`); process.exit(1); }
  console.log('reproducible: every output is byte-for-byte the same');
}
